export interface ProductImageLookup {
  id?: string;
  rawName?: string;
  name?: string;
  brand?: string;
}

/**
 * Resolves a verified `/products/<filename>` URL for a perfume,
 * or returns `undefined` when no physical image file exists in `/public/products/`.
 */
export function resolveProductImageUrl(input: ProductImageLookup): string | undefined {
  const rawCandidates = [
    input.id,
    input.rawName,
    input.name && input.brand ? `${input.name}---${input.brand}` : undefined,
    input.name && input.brand ? `${input.name}-${input.brand}` : undefined,
  ].filter((v): v is string => Boolean(v && v.trim().length > 0));

  for (const raw of rawCandidates) {
    const stem = raw.trim().toLowerCase();
    const exact = byExactStem.get(stem);
    if (exact) return exact;
  }

  for (const raw of rawCandidates) {
    const comp = compactSlug(raw);
    if (!comp) continue;

    const aliasFile = IMAGE_ALIASES[comp];
    if (aliasFile && EXISTING_FILES_SET.has(aliasFile)) {
      return `/products/${aliasFile}`;
    }

    const compMatch = byCompactSlug.get(comp);
    if (compMatch) return compMatch;
  }

  return undefined;
}
