const EXISTING_FILES_SET = new Set<string>(PRODUCT_IMAGE_FILES);

function compactSlug(input: string): string {
  return String(input || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/---+/g, '-')
    .replace(/[^a-z0-9]/g, '');
}

const byExactStem = new Map<string, string>();
const byCompactSlug = new Map<string, string>();

for (const filename of PRODUCT_IMAGE_FILES) {
  const stem = filename.replace(/\.[^.]+$/, '').toLowerCase();
  const publicPath = `/products/${filename}`;
  byExactStem.set(stem, publicPath);
  const comp = compactSlug(stem);
  if (comp && !byCompactSlug.has(comp)) {
    byCompactSlug.set(comp, publicPath);
  }
}

